    function initCustomSelect(root, onSelect) {
        if (!root) return null;
        var trigger = root.querySelector('.select-trigger');
        var list = root.querySelector('.select-options');
        var options = Array.prototype.slice.call(root.querySelectorAll('[role="option"]'));
        var textEl = trigger ? trigger.querySelector('span[data-role]') : null;
        if (!trigger || !list || !options.length) return null;

        function close() {
            root.classList.remove('is-open');
            trigger.setAttribute('aria-expanded', 'false');
            list.hidden = true;
        }
        function open() {
            root.classList.add('is-open');
            trigger.setAttribute('aria-expanded', 'true');
            list.hidden = false;
        }
        function selectOption(opt) {
            options.forEach(function (o) { o.setAttribute('aria-selected', 'false'); o.classList.remove('is-active'); });
            opt.setAttribute('aria-selected', 'true');
            opt.classList.add('is-active');
            if (textEl) { textEl.textContent = opt.textContent; }
            close();
            if (onSelect) { onSelect(opt); }
        }

        trigger.addEventListener('click', function () {
            root.classList.contains('is-open') ? close() : open();
        });

        options.forEach(function (opt) {
            opt.addEventListener('click', function () { selectOption(opt); });
            opt.addEventListener('keydown', function (e) {
                if (e.key === 'Enter' || e.key === ' ') { e.preventDefault(); selectOption(opt); }
                if (e.key === 'Escape') { close(); trigger.focus(); }
            });
        });

        document.addEventListener('click', function (e) {
            if (!root.contains(e.target)) { close(); }
        });
        document.addEventListener('keydown', function (e) {
            if (e.key === 'Escape' && root.classList.contains('is-open')) { close(); trigger.focus(); }
        });

        return { getSelected: function () { return options.filter(function (o) { return o.getAttribute('aria-selected') === 'true'; })[0] || options[0]; } };
    }

    (function initBookingWidget() {
        var seatsOut = document.querySelector('[data-role="seats"]');
        var countOut = document.querySelector('[data-role="count"]');
        var totalOut = document.querySelector('[data-role="total"]');
        var decBtn = document.querySelector('[data-action="decrement"]');
        var incBtn = document.querySelector('[data-action="increment"]');

        if (!countOut || !totalOut) return;

        var persons = 1;
        var MIN_PERSONS = 1;
        var MAX_PERSONS = 10;
        var currentPrice = 12500;

        function formatINR(num) {
            return num.toLocaleString('en-IN');
        }

        function recalc() {
            var total = currentPrice * persons;
            totalOut.textContent = formatINR(total);
            countOut.textContent = persons;
        }

        var categoryCtl = initCustomSelect(document.querySelector('[data-select="category"]'), function (opt) {
            currentPrice = parseInt(opt.getAttribute('data-value'), 10) || 0;
            recalc();
        });
        var slotCtl = initCustomSelect(document.querySelector('[data-select="slot"]'), function (opt) {
            var seats = opt.getAttribute('data-seats');
            if (seats && seatsOut) { seatsOut.textContent = seats; }
        });

        if (categoryCtl) {
            var initialCategory = categoryCtl.getSelected();
            if (initialCategory) { currentPrice = parseInt(initialCategory.getAttribute('data-value'), 10) || currentPrice; }
        }

        if (decBtn) {
            decBtn.addEventListener('click', function () {
                if (persons > MIN_PERSONS) { persons--; recalc(); }
            });
        }
        if (incBtn) {
            incBtn.addEventListener('click', function () {
                if (persons < MAX_PERSONS) { persons++; recalc(); }
            });
        }
        recalc();
    })();

    (function initScrollReveal() {
        var items = document.querySelectorAll('.reveal');
        if (!items.length) return;

        var reduceMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
        if (reduceMotion || !('IntersectionObserver' in window)) {
            items.forEach(function (el) { el.classList.add('is-visible'); });
            return;
        }

        var observer = new IntersectionObserver(function (entries) {
            entries.forEach(function (entry) {
                if (entry.isIntersecting) {
                    entry.target.classList.add('is-visible');
                    observer.unobserve(entry.target);
                }
            });
        }, { threshold: 0.12, rootMargin: '0px 0px -40px 0px' });

        items.forEach(function (el) { observer.observe(el); });
    })();
</script>
